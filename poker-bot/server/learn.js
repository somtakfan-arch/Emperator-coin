import { newDeck, shuffle, evaluate, describeHand } from '../core/cards.js';

// ---------- Викторина: 10 вопросов, у кого рука сильнее ----------

export function quiz(n = 10) {
  const out = [];
  while (out.length < n) {
    const d = shuffle(newDeck());
    const board = d.slice(0, 5), a = d.slice(5, 7), b = d.slice(7, 9);
    const va = evaluate(a.concat(board)), vb = evaluate(b.concat(board));
    if (va === vb && Math.random() < 0.8) continue; // ничьи — редко
    out.push({ board, a, b, answer: va > vb ? 'a' : vb > va ? 'b' : 'tie', aName: describeHand(va), bName: describeHand(vb) });
  }
  return out;
}

