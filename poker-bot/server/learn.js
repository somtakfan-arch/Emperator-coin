export const EXAM_SIZE = 15;
export const EXAM_PASS = 12;

// вопросы без ответов; набор выбирается случайно, id — номер в общем списке
export function examQuestions() {
  return shuffle(EXAM.map((x, i) => ({ id: i, q: x.q, a: x.a }))).slice(0, EXAM_SIZE);
}
export function gradeExam(answers) {
  const list = Object.entries(answers || {}).filter(([id]) => EXAM[Number(id)]);
  if (list.length !== EXAM_SIZE) throw new Error(`Ответь на все ${EXAM_SIZE} вопросов`);
  const right = list.filter(([id, v]) => EXAM[Number(id)].ok === Number(v)).length;
  const wrong = list.filter(([id, v]) => EXAM[Number(id)].ok !== Number(v)).map(([id]) => ({ q: EXAM[Number(id)].q, right: EXAM[Number(id)].a[EXAM[Number(id)].ok] }));
  return { right, total: EXAM_SIZE, passed: right >= EXAM_PASS, wrong };
}
