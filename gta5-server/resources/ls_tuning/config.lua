-- Как машины едут.
--
-- В ваниле у каждой машины свой потолок скорости (fInitialDriveMaxFlatVel в
-- handling.meta) и довольно вялый разгон. На RP-серверах это обычно
-- разгоняют: тут то же самое, но настройками, а не правкой хендлинга -
-- правка файлов хендлинга разошлась бы с аддонами.
--
-- Всё это накладывается на машину, когда игрок в неё садится, и слетает
-- само, когда машина исчезает.
Config.Drive = {
    enabled = true,

    -- ---------------------------------------------------------------------
    -- Скорость задаётся целевой цифрой в км/ч, а не прибавкой в процентах.
    --
    -- Проценты не работают для задачи "норм тачка едет 250": у каждой модели
    -- своя заводская максималка, и +22% превращают одну в 190, а другую в
    -- 340. Поэтому считаем множитель под конкретную цель:
    --
    --     ModifyVehicleTopSpeed(veh, цель / GetVehicleEstimatedMaxSpeed(veh))
    --
    -- Что считать дорогой машиной, решает не список моделей, а цена в
    -- каталоге автосалона: сервер строит таблицу модель -> км/ч сам, и она
    -- не разъезжается с ценником, когда каталог правят.
    -- ---------------------------------------------------------------------

